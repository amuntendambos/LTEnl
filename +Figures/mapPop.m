for i=3:max(topo_wgs(:,1))-1
    II=find(topo_wgs(:,1)==i);
    hline2=plot(topo_wgs(II,2),topo_wgs(II,3),'Color',[0.5 0.5 0.5]);
    if i==1
        set(get(get(hline2,'Annotation'),'LegendInformation'),...
            'IconDisplayStyle','on');
    else
        set(get(get(hline2,'Annotation'),'LegendInformation'),...
            'IconDisplayStyle','off');
